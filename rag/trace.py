"""OS Lab - Predict, Run, Explain: an algorithm's run as a sequence of events to step through.

    events(problem) -> list[Event]

Every event comes from the real solver's run (rag.solver steps, rag.banker checks, rag.paging and
rag.disk runs): the state before a decision, a question asking the student to predict the decision,
the actual decision, the solver's own explanation of it, and the state after it. Nothing is
generated by the LLM. tests/test_trace.py checks that replaying the events reproduces the solver's
result exactly.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from . import banker, disk, paging, solver
from .numericals import kind as kind_of


@dataclass
class Event:
    title: str                      # "t = 4"
    question: str                   # what to predict
    options: list[str]
    answer: int                     # index of the right option
    explanation: str                # the solver's own account of the decision
    before: dict                    # state shown while predicting
    after: dict                     # state once the event has run
    data: dict = field(default_factory=dict)   # for drawing (kind-specific)


@dataclass
class Lab:
    kind: str
    problem: object
    solution: object
    events: list[Event]
    reflection: str                 # a closing question


def events(problem) -> Lab:
    return {"scheduling": _scheduling, "banker": _banker, "paging": _paging, "disk": _disk}[kind_of(problem)](problem)


def event_for(lab: Lab, where: str) -> int:
    """The lab event a Reasoning Debugger finding refers to ("Gantt chart at t=5", "reference 4 (page 2)",
    "service order, request 3", "safe sequence, position 2"); 0 if there is none."""
    if lab.kind == "scheduling":
        m = re.search(r"t=(\d+)", where)
        if m:
            t = int(m.group(1))
            times = [e.data["step"]["t"] for e in lab.events]
            return max((i for i, x in enumerate(times) if x <= t), default=0)
    m = re.search(r"(?:reference|request) (\d+)", where)
    if m and lab.kind in ("paging", "disk"):
        return int(m.group(1)) - 1
    return 0


@dataclass
class Session:
    """A student's walk through a lab: predictions, which events have been run, where they are."""
    lab: Lab
    pos: int = 0
    predictions: dict = field(default_factory=dict)   # event index -> chosen option
    ran: set = field(default_factory=set)             # event indices whose outcome has been shown

    @property
    def event(self) -> Event | None:
        return self.lab.events[self.pos] if self.pos < len(self.lab.events) else None

    @property
    def done(self) -> bool:
        return self.pos >= len(self.lab.events)

    def predict(self, option: int):
        if self.pos not in self.ran:                  # a prediction is locked once the event has run
            self.predictions[self.pos] = option

    def run(self):
        self.ran.add(self.pos)

    def next(self):
        if self.pos in self.ran and not self.done:
            self.pos += 1

    def previous(self):
        self.pos = max(0, self.pos - 1)

    def jump(self, pos: int):
        """Open the lab at event `pos` (e.g. where a student's own working went wrong); the
        events before it count as already run, without predictions."""
        self.pos = max(0, min(pos, len(self.lab.events) - 1))
        self.ran |= set(range(self.pos))

    def replay(self):
        """Back to the start, keeping the predictions and outcomes already seen."""
        self.pos = 0

    def reset(self):
        self.pos, self.predictions, self.ran = 0, {}, set()

    def score(self) -> tuple[int, int]:
        """(right predictions, predictions made) over the events that have run."""
        made = [i for i in self.ran if i in self.predictions]
        return sum(self.predictions[i] == self.lab.events[i].answer for i in made), len(made)


# ---------------------------------------------------------------------------------------
# CPU scheduling (Round Robin first; every algorithm of rag.solver works the same way)
# ---------------------------------------------------------------------------------------
REFLECTION = {
    "rr": "Would a larger quantum lower the average waiting time here? What happens to Round Robin when the "
          "quantum is larger than every burst?",
    "fcfs": "Which process waited longest, and would SJF have helped it? Where do you see the convoy effect?",
    "sjf": "Which process could starve if short jobs kept arriving?",
    "srtf": "How many preemptions happened, and which arrival caused each one?",
    "priority": "Which process could starve under priority scheduling, and how would aging help?",
    "priority_p": "Which preemptions would not have happened under non-preemptive priority?",
}


def _sched_label(pid) -> str:
    return "CPU idle" if pid is None else f"P{pid}"


def _scheduling(p: solver.Problem) -> Lab:
    s = solver.solve(p)
    procs = {q.pid: q for q in p.procs}
    out = []
    dispatched = {}                                # pid -> when it last got the CPU (Round Robin quantum)
    for k, st in enumerate(s.steps):
        if st["action"] == "end":
            break
        cands = list(st["ready"])
        before_run = st["before"]
        if before_run is not None and before_run not in st["completed"] + st["to_io"] \
                and before_run != st["expired"] and before_run not in cands:
            cands.append(before_run)
        options = [f"P{x}" for x in sorted(cands)] + ["CPU idle"]
        answer = options.index(_sched_label(st["after"]))
        after_ready = [x for x in st["ready"] if x != st["after"]] + \
            ([st["preempted"]] if st["preempted"] and st["preempted"] != st["after"] else [])
        happened = ([f"P{x} arrives" for x in st["arrived"]] + [f"P{x} returns from I/O" for x in st["returned"]]
                    + [f"P{x} completes" for x in st["completed"]] + [f"P{x} starts I/O" for x in st["to_io"]]
                    + ([f"P{st['expired']}'s quantum expires"] if st["expired"] else []))
        gantt_so_far = [(l, a, min(b, st["t"])) for l, a, b in s.gantt if a < st["t"]]
        before = {"time": st["t"], "running": _sched_label(before_run), "events": happened,
                  "ready": [f"P{x}" for x in st["ready"]],
                  "remaining": {f"P{x}": r for x, r in st["remaining"].items() if procs[x].at <= st["t"]},
                  "gantt": gantt_so_far}
        if p.algo == "rr":
            before["quantum"] = p.quantum
            before["used"] = st["t"] - dispatched[before_run] if before_run is not None else 0
        after = {"time": st["t"], "running": _sched_label(st["after"]), "ready": [f"P{x}" for x in after_ready],
                 "action": st["action"], "preempted": None if st["preempted"] is None else f"P{st['preempted']}"}
        out.append(Event(f"t = {st['t']}", f"At t = {st['t']}, which process runs next?", options, answer,
                         s.trace[k], before, after, {"step": st}))
        if st["action"] in ("dispatch", "preempt"):
            dispatched[st["after"]] = st["t"]
    return Lab("scheduling", p, s, out, REFLECTION[p.algo])


# ---------------------------------------------------------------------------------------
# Banker's algorithm: each comparison of Need with Work
# ---------------------------------------------------------------------------------------
def _banker(p: banker.Problem) -> Lab:
    s = banker.solve(p)
    vec = lambda v: "(" + " ".join(map(str, v)) + ")"
    out = []
    finished: list[str] = []
    label = "Request" if p.detect else "Need"
    for c in s.check.checks:
        nm = f"{p.prefix}{p.pids[c['i']]}"
        before = {"pass": c["pass"], "process": nm, label.lower(): vec(c["need"]), "work": vec(c["work"]),
                  "finished": list(finished)}
        if c["ok"]:
            finished.append(nm)
        after = {**before, "work": vec(c.get("work_after", c["work"])), "finished": list(finished)}
        out.append(Event(f"Pass {c['pass']}: {nm}", f"Can {nm} finish now ({label} {vec(c['need'])}, Work "
                                                     f"{vec(c['work'])})?",
                         ["Yes: its " + label + " fits in Work", "No: it must wait"], 0 if c["ok"] else 1,
                         s.check.steps[c["step"]], before, after, {"check": c}))
    return Lab("banker", p, s, out, "Is the safe sequence you found the only one? Try starting with a different "
                                    "process whose Need fits in Available.")


# ---------------------------------------------------------------------------------------
# Page replacement: each reference
# ---------------------------------------------------------------------------------------
def _paging(p: paging.Problem) -> Lab:
    s = paging.solve(paging.Problem(p.refs, p.frames[:1], p.algos[:1]))
    run = s.runs[0]
    out = []
    frames: list = [None] * run.frames
    for t, page in enumerate(p.refs):
        resident = [x for x in frames if x is not None]
        options = ["Hit"] + (["Fault: load into a free frame"] if None in frames else
                             [f"Fault: replace page {x}" for x in resident])
        if not run.faults[t]:
            answer = 0
        elif run.victims[t] is None:
            answer = 1
        else:
            answer = options.index(f"Fault: replace page {run.victims[t]}")
        before = {"reference": f"{t + 1} of {len(p.refs)}", "page": page,
                  "frames": " ".join("-" if x is None else str(x) for x in frames)}
        frames = list(run.table[t])
        after = {**before, "frames": " ".join("-" if x is None else str(x) for x in frames),
                 "result": "hit" if not run.faults[t] else "fault"}
        out.append(Event(f"Reference {t + 1}: page {page}", f"Page {page} is referenced. What happens with "
                                                            f"{paging.SHORT[run.algo]}?",
                         options, answer, run.steps[t], before, after, {"t": t}))
    return Lab("paging", p, s, out, "Would one more frame always mean fewer faults? (Try FIFO on 1 2 3 4 1 2 5 1 2 "
                                    "3 4 5 with 3 and 4 frames.)")


# ---------------------------------------------------------------------------------------
# Disk scheduling: each head movement
# ---------------------------------------------------------------------------------------
def _disk(p: disk.Problem) -> Lab:
    q = disk.Problem(p.requests, p.head, p.algos[:1], p.up, p.cylinders, p.count_return, p.assumed)
    s = disk.solve(q)
    run = s.runs[0]
    steps = [x for x in run.steps if "->" in x]    # one line per move (the first line is the set-up)
    pending = list(p.requests)
    out = []
    for i, (a, b) in enumerate(zip(run.path, run.path[1:])):
        ends = [c for c in (0, p.cylinders - 1) if c not in pending and run.algo in ("scan", "cscan")]
        options = [str(c) for c in sorted(set(pending))] + [f"{c} (end of disk)" for c in ends]
        right = str(b) if b in pending else f"{b} (end of disk)"
        if right not in options:
            options.append(right)
        before = {"head": a, "pending": ", ".join(map(str, sorted(pending))), "moved so far": sum(run.moves[:i])}
        serves = b in pending and (i not in run.jumps or run.algo == "clook")   # C-SCAN's jump serves nothing
        if serves:
            pending.remove(b)
        after = {**before, "head": b, "pending": ", ".join(map(str, sorted(pending))),
                 "moved so far": sum(run.moves[:i + 1])}
        out.append(Event(f"Move {i + 1}", f"The head is at {a}. Where does {disk.SHORT[run.algo]} send it next?",
                         options, options.index(right), steps[i] if i < len(steps) else "",
                         before, after, {"move": i}))
    return Lab("disk", q, s, out, "Which algorithm would have needed the least head movement for this queue, and "
                                  "would it be fair to the requests at the edges?")
